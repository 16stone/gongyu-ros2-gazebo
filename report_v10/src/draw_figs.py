FONT='/usr/share/fonts/truetype/droid/DroidSansFallbackFull.ttf'
def f(sz):return ImageFont.truetype(FONT,sz)
INK=(30,42,58);BLUE=(22,103,184);RED=(201,67,53);GOLD=(224,170,60);GRID=(222,231,239);GRAY=(110,128,146)
def canvas(w,h,title):
    im=Image.new('RGB',(w,h),(255,255,255));d=ImageDraw.Draw(im)
    d.rectangle([0,0,w-1,h-1],outline=(210,220,230),width=1)
    d.text((24,16),title,font=f(19),fill=INK)
    return im,d

# Fig 1 trajectories
rp=json.load(open(REPO+'/docs/demo/webots_replay_data.json',encoding='utf-8'))
im,d=canvas(940,540,'Fig.1  Eight-entity trajectories, f-webots-full-01')
L,T,R,B=60,58,900,490
def sx(x):return L+(x+3)/25*(R-L)
def sy(y):return T+(11-y)/24*(B-T)
for xv in range(-2,23,2):
    x=sx(xv);d.line([(x,T),(x,B)],fill=GRID,width=1);d.text((x-6,B+6),str(xv),font=f(11),fill=GRAY)
for yv in range(-14,11,2):
    y=sy(yv);d.line([(L,y),(R,y)],fill=GRID,width=1);d.text((L-28,y-6),str(yv),font=f(11),fill=GRAY)
d.rectangle([sx(2.05),sy(.6),sx(4.95),sy(-.6)],fill=(250,241,219),outline=GOLD,width=2)
d.text((sx(2.05)+6,sy(.6)-20),'SHARED CHANNEL',font=f(12),fill=(150,110,25))
for nid,(x,y) in rp['nodes'].items():
    if len(nid)<=2:
        d.ellipse([sx(x)-2,sy(y)-2,sx(x)+2,sy(y)+2],fill=(140,165,189))
        d.text((sx(x)+4,sy(y)-13),nid,font=f(10),fill=(110,135,158))
for n,rows in rp['trajectories'].items():
    if not rows:continue
    col=BLUE if n.startswith('B') else RED
    pts=[(sx(r[1]),sy(r[2])) for r in rows]
    if len(pts)>1:d.line(pts,fill=col,width=2)
    for p in pts[::3]:d.ellipse([p[0]-2,p[1]-2,p[0]+2,p[1]+2],fill=col)
    if pts:d.text((pts[-1][0]+6,pts[-1][1]-6),n,font=f(12),fill=col)
d.text((60,510),'x / m                                                                                      y / m',font=f(12),fill=GRAY)
im.save(FIG+'/trajectory.png')

# Fig 2 localization RMSE bars
def bars(path,title,labels,values,ylab,maxv=None):
    im,d=canvas(680,360,title)
    L,T,R,B=82,74,630,290
    d.line([(L,B),(R,B)],fill=(150,165,180),width=2)
    mx=maxv or max(values)*1.25
    for i,(lab,v) in enumerate(zip(labels,values)):
        x=L+90+i*240;h=int((B-T)*v/mx)
        col=BLUE if i==0 else RED
        d.rectangle([x,B-h,x+110,B],fill=col)
        d.text((x+16,B-h-30),'%.3f'%v if isinstance(v,float) else str(v),font=f(17),fill=INK)
        d.text((x+5,B+12),lab,font=f(13),fill=INK)
    d.text((20,44),ylab,font=f(13),fill=GRAY)
    im.save(path)

