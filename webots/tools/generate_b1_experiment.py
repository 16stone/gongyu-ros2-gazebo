#!/usr/bin/env python3
"""Generate isolated Phase B worlds using the frozen physical B1 chassis."""
import os
from pathlib import Path
import re
import sys

os.environ["GONGYU_WORLD_PHYS"] = "1"
from generate_world import pbr, pos, robot_ugv, shape_box, solid

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "common"))
from b1_experiment import CARD


layouts = {**CARD["layouts"], "gate": CARD["layouts"]["narrow"], "unmapped": CARD["layouts"]["lowobs"]}
for layout, boxes in layouts.items():
    start = CARD["start"]
    chassis = robot_ugv("B1", *start).replace("gongyu_ugv", "gongyu_b1_trial")
    sensors = CARD["sensors"]
    for mode in ("main", "low"):
        sensor = sensors[mode]
        node = (f'Lidar {{ name "lidar_{mode}" translation {sensor["x_m"]} 0 {sensor["z_local_m"]} '
                f'projection "cylindrical" horizontalResolution {sensors["samples"]} '
                f'numberOfLayers 1 fieldOfView {sensors["field_of_view_rad"]} '
                f'minRange {sensor["min_m"]} maxRange {sensor["max_m"]} }}')
        chassis, replaced = re.subn(r'Lidar \{ name "lidar_' + mode + r'"[^}]*\}', node, chassis)
        assert replaced == 1
    lines = ['#VRML_SIM R2025a utf8', '# Generated by webots/tools/generate_b1_experiment.py',
             f'WorldInfo {{ basicTimeStep {sensors["step_ms"]} title "B1 Phase B {layout}" randomSeed 0 }}',
             'Viewpoint { position 3 -7 8 orientation 1 0 0 0.65 }',
             'Background { skyColor [ 0.13 0.18 0.24 ] }',
             'DirectionalLight { direction -0.4 0.3 -1 intensity 2.2 }',
             solid("floor", pos(3.2, 0, -0.08), shape_box((10, 6, 0.16), pbr((0.15, 0.19, 0.24))),
                   bounding="Box { size 10 6 0.16 }")]
    for name, x0, x1, y0, y1, h in boxes:
        size = round(x1 - x0, 4), round(y1 - y0, 4), h
        bbox = f"Box {{ size {size[0]} {size[1]} {size[2]} }}"
        lines.append(solid(name, pos((x0+x1)/2, (y0+y1)/2, h/2),
                           shape_box(size, pbr((0.90, 0.64, 0.11))), bounding=bbox))
    if layout == "gate":
        lines.append(robot_ugv("B2", *CARD["gate"]["peer_start"]))
    lines.extend((chassis, 'Robot { name "B1 judge" supervisor TRUE controller "gongyu_b1_judge" }'))
    scene = f"web_b1_{layout}" if layout in ("gate", "unmapped") else f"web_b1_phaseb_{layout}"
    (ROOT / "worlds" / f"{scene}.wbt").write_text("\n".join(lines) + "\n")
