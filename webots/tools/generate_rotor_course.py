#!/usr/bin/env python3
"""Build the rotor course world from the verified ground scene and multirotor model."""
import re
from pathlib import Path


def main():
    worlds = Path(__file__).resolve().parents[1] / "worlds"
    ground = (worlds / "web_medium_phys.wbt").read_text(encoding="utf-8")
    flight = (worlds / "web_course_b3_flight.wbt").read_text(encoding="utf-8")
    panel = flight.split('Solid {\n  name "worksite panel"', 1)[1].split("DEF COVER", 1)[0]
    panel = ('Solid {\n  name "worksite panel"' + panel).replace("2.2 0.8", "14 8")
    panel = panel.replace("  boundingObject Box { size 0.70 0.70 0.030 }\n", "")
    rotor = "DEF B3 Robot {" + flight.split("DEF B3 Robot {", 1)[1].split("\nRobot {", 1)[0]
    blue = rotor.replace("translation 0 0 0.052", "translation 14 8 0.052")
    red = rotor.replace("DEF B3", "DEF R5").replace('"B3"', '"R5"')
    red = red.replace("translation 0 0 0.052", "translation 14 -8 0.052")
    red = red.replace("0.10 0.52 0.92", "0.93 0.30 0.17")
    ground = ground.replace('title "web_medium_phys"', 'title "web_medium_rotor_phys"')
    ground = ground.replace("# generated by webots/tools/generate_world.py;",
                            "# generated by webots/tools/generate_rotor_course.py;")
    text, replaced = re.subn(r"^DEF B3 Robot \{.*?(?=^Robot \{ name \"referee\")",
                             lambda _: "\n".join((panel.rstrip(), blue.rstrip(), red.rstrip(), "")), ground, flags=re.M | re.S)
    if replaced != 1:
        raise ValueError("Expected the B3 and R5 blocks before the referee")
    (worlds / "web_medium_rotor_phys.wbt").write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
