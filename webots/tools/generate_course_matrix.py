"""Build the logistics matrix scenes using the existing motor chassis."""

import os
from pathlib import Path
import sys

os.environ["GONGYU_WORLD_PHYS"] = "1"
from generate_world import pbr, pos, robot_ugv, shape_box, solid

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "common"))
from course_matrix import STARTS


def box(name, x, y, z, size, color):
    bounds = "Box { size " + " ".join(map(str, size)) + " }"
    return solid(name, pos(x, y, z), shape_box(size, pbr(color)), bounding=bounds)


for scene, starts in STARTS.items():
    nodes = [
        "#VRML_SIM R2025a utf8",
        "# Generated by webots/tools/generate_course_matrix.py",
        f'WorldInfo {{ basicTimeStep 16 title "{scene}" randomSeed 0 }}',
        "Viewpoint { position 3 -8 18 orientation 1 0 0 0.1 }",
        "Background { skyColor [ 0.13 0.18 0.24 ] }",
        "DirectionalLight { direction -0.4 0.3 -1 intensity 2.2 }",
        box("floor", 4, -5.5, -0.08, (16, 18, 0.16), (0.15, 0.19, 0.24)),
    ]
    if scene in {"web_long", "web_medium_exit"}:
        for side, y in (("south", -0.55), ("north", 0.55)):
            nodes.append(box(f"channel_rail_{side}", 3.5, y, 0.30, (3.2, 0.08, 0.60),
                             (0.30, 0.32, 0.38)))
    nodes.extend(robot_ugv(actor, *xy) for actor, xy in starts.items())
    nodes.append('Robot { name "matrix judge" supervisor TRUE controller "course_matrix_referee" }')
    (ROOT / "worlds" / f"{scene}.wbt").write_text("\n".join(nodes) + "\n", encoding="utf-8")
